// Encabezado (Definición de Registros, Variables y Constantes)
.include "M328PDEF.inc"     // Include definitions specific to ATMega328P
.dseg
.org    SRAM_START

MIN_UNIDADES:	.byte 1
MIN_DECENAS:	.byte 1
HRS_UNIDADES:	.byte 1
HRS_DECENAS:	.byte 1
DIAS_UNIDADES:	.byte 1
DIAS_DECENAS:	.byte 1
HRS_U_MOD:		.byte 1
HRS_D_MOD:		.byte 1
MIN_U_MOD:		.byte 1
MIN_D_MOD:		.byte 1
MES_UNIDADES:	.byte 1
MES_DECENAS:	.byte 1
ESTADO_ANT:		.byte 1
ESTADO_ANT_ALM: .byte 1

DIA:	.byte 1
MES:	.byte 1

MIN_UNIDADES_ALM:       .byte 1
MIN_DECENAS_ALM:       .byte 1
HRS_UNIDADES_ALM:       .byte 1
HRS_DECENAS_ALM:       .byte 1

DISP_ACTUAL:     .byte 1
BANDERAS:        .byte 1
//variable_name:     .byte   1   // Memory alocation for variable_name:     .byte   (byte size)
//1B1E

.equ T0VALUE		= 0xB1
.equ T1VALUE		= 0x1B1E
.equ T2VALUE		= 0xF6
.equ MAX_MODOS		= 8
.def MODO			= R19
.def BANDERA_SUMA	= R20
.def BANDERA_RESTA	= R24

.cseg
.org 0x0000
	JMP START

.org PCI1addr
	JMP PC_ISR

.org OVF2addr
	JMP TMR2_ISR

.org OVF1addr
	JMP TMR1_ISR
	
.org OVF0addr
	JMP TMR0_ISR

disp7seg:
	.db 0x40, 0x79, 0x24, 0x30,	0x19, 0x12,	0x02, 0x78, 0x00, 0x10, 0x08, 0x03, 0x46, 0x21, 0x06, 0x0E

START:
/****************************************/
// Configuración de la pila
LDI     R16, LOW(RAMEND)
OUT     SPL, R16
LDI     R16, HIGH(RAMEND)
OUT     SPH, R16

CLR R16
STS MIN_UNIDADES, R16
STS MIN_DECENAS, R16
STS HRS_UNIDADES, R16
STS HRS_DECENAS, R16
STS DIAS_DECENAS, R16
STS MES_DECENAS, R16

LDI R16, 2
STS HRS_DECENAS_ALM, R16
LDI R16, 3
STS HRS_UNIDADES_ALM, R16
LDI R16, 5
STS MIN_DECENAS_ALM, R16
LDI R16, 9
STS MIN_UNIDADES_ALM, R16

LDI R16, 1
STS DIAS_UNIDADES, R16
STS MES_UNIDADES, R16

/****************************************/
// Configuracion MCU
SETUP:
	//Desactivar TX y DX en D0 y D1
	CLR r16
	STS UCSR0B, r16

	// Prescaler del reloj del sistema
    LDI		R16, (1 << CLKPCE)
	STS		CLKPR, R16 // Permitir el prescaler del sistema
	LDI		R16, (1 << CLKPS2)
	STS		CLKPR, R16 //Poner el prescaler en 16
	
	//Salidas y entradas
		//Puerto D
		LDI		R16, 0xFF // Cargando valor para poner todos los pines como salida
		OUT		DDRD, R16

		// Configuracion para que los display muestren 0 al inicio
			LDI		ZH, HIGH(disp7seg<<1)
			LDI		ZL, LOW(disp7seg<<1)

			LPM		r16, Z
			ORI		R16, 0b10000000
			OUT		PORTD, r16 //Para que muestre 0 inicialmente

		//Puerto C
		LDI R16, 0b00111000 // Para que los pines 3, 4 y 5 sean salidas
		OUT DDRC, R16
		LDI R16, 0b00000111 // Activar Pull-up interno para los pines del 0 al 3
		OUT PORTC, R16

		IN R16, PINC
		STS ESTADO_ANT, R16

		//Puerto B
		LDI R16, 0b00011111 // Valor para activar las salidas del puerto B
		OUT DDRB, R16
		LDI R16, 0b00001111 // Empezar con todos los displays en 0
		OUT PORTB, R16

	//Configurar el Timer 0
	CALL INIT_TIMER0
	LDI R16, 0b00000111
	OUT PORTC, R16
	//Configurar el Timer 1
	CALL INIT_TIMER1

	//Configurar el Timer 2
	CALL INIT_TIMER2

	LDI R16, 0b00000111 // Activar Pull-up interno para los pines del 0 al 3
	OUT PORTC, R16

	//Habilitar interrupciones
		// Pin Change
		LDI R16, (1 << PCIE1)
		STS PCICR, R16 // Habilitando la interrupcion en el PINC

		LDI R16, (1 << PCINT10)|(1 << PCINT9)|(1 << PCINT8)
		STS PCMSK1, R16 // Habilitando los pines del 0 al 2
	
		//Mascara del timer0
		LDI R16, (1 << TOIE0)
		STS TIMSK0, R16 

		//Mascara del timer1
		LDI R16, (1 << TOIE1)
		STS TIMSK1, R16

		//Mascara del timer2
		LDI R16, (1 << TOIE2)
		STS TIMSK2, R16

		//Borrar registros
		CLR MODO
		CLR BANDERA_SUMA
		CLR BANDERA_RESTA
		CLR R1
		CLR R16
		CLR R18
		CLR R21
		CLR R22
		CLR R23
		CLR R25
		CLR R27
		CLR R28
		CLR R29
		IN	R17, PINC
		STS	ESTADO_ANT, R17
		CLR R17
		

	//HABILITAR INTERRUPCIONES GLOBALES
	SEI

/****************************************/
// Loop Infinito
MAIN_LOOP:
	//Verificar bandera del dia
	LDS     R16, BANDERAS
    SBRS    R16, 0
    RJMP    CONTINUAR_MAIN
    CLR		R16
    STS     BANDERAS, R16
    CALL	VERIFICAR_MES

	CONTINUAR_MAIN:
	CPI MODO, 0
	BREQ CONTINUAR_0
	CPI MODO, 1
	BREQ CONTINUAR_1
	CPI MODO, 2
	BREQ CONTINUAR_2
	CPI MODO, 3
	BREQ CONTINUAR_3
	CPI MODO, 4
	BREQ CONTINUAR_4
	CPI MODO, 5
	BREQ CONTINUAR_5
	CPI MODO, 6
	BREQ CONTINUAR_6
	CPI MODO, 7
	BREQ CONTINUAR_7

	CONTINUAR_0:
		RJMP MODO_0
	CONTINUAR_1:
		RJMP MODO_1
	CONTINUAR_2:
		RJMP MODO_2
	CONTINUAR_3:
		RJMP MODO_3
	CONTINUAR_4:
		RJMP MODO_4
	CONTINUAR_5:
		RJMP MODO_5
	CONTINUAR_6:
		RJMP MODO_6
	CONTINUAR_7:
		RJMP MODO_7

	RJMP MAIN_LOOP

	//MODO RELOJ
	MODO_0:
		SBI PORTC, PORTC3
		CBI PORTC, PORTC4
		CBI PORTC, PORTC5

		CALL COMPARAR_ALM

		//Multiplexado del reloj
		CALL	MOSTRAR_UNI_MIN
		SBI		PORTB, PORTB3
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB3

		CALL	MOSTRAR_DEC_MIN
		SBI		PORTB, PORTB2
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB2

		CALL	MOSTRAR_UNI_HRS
		SBI		PORTB, PORTB1
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB1

		CALL	MOSTRAR_DEC_HRS
		SBI		PORTB, PORTB0
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB0

		SIGUE_MOD0:
			CLR BANDERA_SUMA
			CLR BANDERA_RESTA
			RJMP SALIDA

	//MODO FECHA
	MODO_1:
		CBI PORTC, PORTC3
		SBI PORTC, PORTC4
		CBI PORTC, PORTC5

		//Multiplexado de la fecha
		CALL	MOSTRAR_UNI_MES
		SBI		PORTB, PORTB3
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB3

		CALL	MOSTRAR_DEC_MES
		SBI		PORTB, PORTB2
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB2

		CALL	MOSTRAR_UNI_DIA
		SBI		PORTB, PORTB1
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB1

		CALL	MOSTRAR_DEC_DIA
		SBI		PORTB, PORTB0
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB0
		
		RJMP SALIDA

	//CONFIGURACION DE LOS MINUTOS
	MODO_2:
		SBI		PORTC, PORTC3
		CBI		PORTC, PORTC4
		SBIC	PIND, PIND7
		SBI		PORTC, PORTC5
		SBIS	PIND, PIND7
		CBI		PORTC, PORTC5

		SBRC BANDERA_SUMA, 0
		CALL SUMAR_M2
		SBRC BANDERA_RESTA, 0
		CALL RESTAR_M2

		//Multiplexado de los minutos
		CBI PORTB, PORTB0
		CBI PORTB, PORTB1

		CALL	MOSTRAR_UNI_MIN
		SBI		PORTB, PORTB3
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB3

		CALL	MOSTRAR_DEC_MIN
		SBI		PORTB, PORTB2
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB2

		RJMP SALIDA

	//CONFIGURACION DE LA HORA
	MODO_3:
		SBI		PORTC, PORTC3
		CBI		PORTC, PORTC4
		SBIC	PIND, PIND7
		SBI		PORTC, PORTC5
		SBIS	PIND, PIND7
		CBI		PORTC, PORTC5

		SBRC BANDERA_SUMA, 0
		CALL SUMAR_M3
		SBRC BANDERA_RESTA, 0
		CALL RESTAR_M3

		//Multiplexado de los minutos
		CBI PORTB, PORTB2
		CBI PORTB, PORTB3

		CALL	MOSTRAR_UNI_HRS
		SBI		PORTB, PORTB1
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB1

		CALL	MOSTRAR_DEC_HRS
		SBI		PORTB, PORTB0
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB0

		RJMP SALIDA


	//CONFIGURACION DEL MES
	MODO_4:
		CBI		PORTC, PORTC3
		SBI		PORTC, PORTC4
		SBIC	PIND, PIND7
		SBI		PORTC, PORTC5
		SBIS	PIND, PIND7
		CBI		PORTC, PORTC5

		SBRC BANDERA_SUMA, 0
		CALL SUMAR_M4
		SBRC BANDERA_RESTA, 0
		CALL RESTAR_M4

		//MULTIPLEXADO MESES
		CBI PORTB, PORTB0
		CBI PORTB, PORTB1

		CALL	MOSTRAR_UNI_MES
		SBI		PORTB, PORTB3
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB3

		CALL	MOSTRAR_DEC_MES
		SBI		PORTB, PORTB2
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB2

		RJMP SALIDA

	//CONFIGURACION DEL DIA
	MODO_5:
		CBI		PORTC, PORTC3
		SBI		PORTC, PORTC4
		SBIC	PIND, PIND7
		SBI		PORTC, PORTC5
		SBIS	PIND, PIND7
		CBI		PORTC, PORTC5

		SBRC BANDERA_SUMA, 0
		CALL SUMAR_M5
		SBRC BANDERA_RESTA, 0
		CALL RESTAR_M5

		CBI PORTB, PORTB2
		CBI PORTB, PORTB3

		CALL	MOSTRAR_UNI_DIA
		SBI		PORTB, PORTB1
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB1

		CALL	MOSTRAR_DEC_DIA
		SBI		PORTB, PORTB0
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB0

		STS HRS_DECENAS_ALM, R1
		STS HRS_UNIDADES_ALM, R1
		STS MIN_DECENAS_ALM, R1
		STS MIN_UNIDADES_ALM, R1

		RJMP SALIDA

	//CONFIGURACION DEL MINUTO DE LA ALARMA
	MODO_6:
		SBI		PORTC, PORTC3
		SBI		PORTC, PORTC4
		SBIC	PIND, PIND7
		SBI		PORTC, PORTC5
		SBIS	PIND, PIND7
		CBI		PORTC, PORTC5

		SBRC BANDERA_SUMA, 0
		CALL SUMAR_M6
		SBRC BANDERA_RESTA, 0
		CALL RESTAR_M6

		//Multiplexado de los minutos
		CBI PORTB, PORTB0
		CBI PORTB, PORTB1

		CALL	MOSTRAR_UNI_MIN_ALM
		SBI		PORTB, PORTB3
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB3

		CALL	MOSTRAR_DEC_MIN_ALM
		SBI		PORTB, PORTB2
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB2

		RJMP SALIDA

	//CONFIGURACION DE LA HORA DE LA ALARMA
	MODO_7:
		SBI		PORTC, PORTC3
		SBI		PORTC, PORTC4
		SBIC	PIND, PIND7
		SBI		PORTC, PORTC5
		SBIS	PIND, PIND7
		CBI		PORTC, PORTC5

		SBRC BANDERA_SUMA, 0
		CALL SUMAR_M7
		SBRC BANDERA_RESTA, 0
		CALL RESTAR_M7

		//Multiplexado de los minutos
		CBI PORTB, PORTB2
		CBI PORTB, PORTB3

		CALL	MOSTRAR_UNI_HRS_ALM
		SBI		PORTB, PORTB1
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB1

		CALL	MOSTRAR_DEC_HRS_ALM
		SBI		PORTB, PORTB0
		OUT		PORTD, R16
		CALL	DELAY
		CBI		PORTB, PORTB0

		RJMP SALIDA

	SALIDA:
		RJMP MAIN_LOOP

/****************************************/
// NON-Interrupt subroutines
INIT_TIMER0:
	PUSH R16

	LDI R16, 0x00 // Valor para timer en modo normal
	STS TCCR0A, R16
	LDI R16, (1 << CS01)|(1 << CS00)// Prescaler
	STS TCCR0B, R16
	LDI R16, T0VALUE // Valor inicial para TCNT
	STS TCNT0, R16

	POP R16
	RET 

INIT_TIMER1: 
	PUSH R16 

	LDI R16, 0x00
	STS TCCR1A, R16 // Poner el timer en modo Normal
	LDI R16, (1 << CS12)|(1 << CS10)
	STS TCCR1B, R16 // Prescaler del reloj
	LDI R16, HIGH(T1VALUE)
	STS TCNT1H, R16 // Cargar valor al TCNT para modo normal
	LDI R16, LOW(T1VALUE)
	STS TCNT1L, R16

	POP R16
	RET 

INIT_TIMER2:
	PUSH R16 

	CLR R16
	STS TCCR2A, R16
	LDI R16, (1 << CS22)|(1 << CS21)
	STS TCCR2B, R16
	LDI R16, T2VALUE
	STS TCNT2, R16

	POP R16
	RET

DELAY:
    LDI R22, 255
	LOOP_DELAY:
		DEC R22
		BRNE LOOP_DELAY
		RET

VERIFICAR_MES:
	LDS R16, MES_UNIDADES
	LDS R17, MES_DECENAS
	CPI	R17, 0
	BREQ PRIMEROS_9_MES
	CPI R16, 0
	BREQ DIAS_31_CALL
	CPI R16, 1
	BREQ DIAS_30
	CPI R16, 2
	BREQ DICIEMBRE_CALL
	RET

DIAS_31_CALL:
	RJMP DIAS_31

DICIEMBRE_CALL:
	RJMP DICIEMBRE
	
PRIMEROS_9_MES:
	CPI R16, 1
	BREQ DIAS_31
	CPI R16, 2
	BREQ DIAS_28_CALL
	CPI R16, 3
	BREQ DIAS_31
	CPI R16, 4
	BREQ DIAS_30 
	CPI R16, 5
	BREQ DIAS_31
	CPI R16, 6
	BREQ DIAS_30
	CPI R16, 7 
	BREQ DIAS_31
	CPI R16, 8
	BREQ DIAS_31
	CPI R16, 9
	BREQ SEPTIEMBRE_CALL
	RET

SEPTIEMBRE_CALL:
	RJMP SEPTIEMBRE

DIAS_28_CALL:
	RJMP DIAS_28

	GUARDAR_DIA:
		STS		DIAS_UNIDADES, R16
		STS		DIAS_DECENAS, R18
		RJMP	SALIDA_MES

	DIAS_30:
		LDS		R16, DIAS_UNIDADES
		INC		R16
		CPI		R16, 1
		BREQ	VERIFICAR_30

		SEGUIR_30:
			CPI		R16, 10
			BRNE	GUARDAR_DIA
			CLR		R16
			STS		DIAS_UNIDADES, R16 
			LDS		R16, DIAS_DECENAS
			INC		R16
			STS		DIAS_DECENAS, R16
			RET
		
		VERIFICAR_30:
			LDS		R18, DIAS_DECENAS
			CPI		R18, 3
			BRNE	SEGUIR_30
			LDS		R16, MES_UNIDADES
			INC		R16
			STS		MES_UNIDADES, R16
			LDI		R16, 1
			STS		DIAS_UNIDADES, R16
			CLR		R16
			STS		DIAS_DECENAS, R16

		RET

	DIAS_31:
		LDS		R16, DIAS_UNIDADES
		INC		R16
		CPI		R16, 2
		BREQ	VERIFICAR_31

		SEGUIR_31:
			CPI		R16, 10
			BRNE	GUARDAR_DIA
			CLR		R16
			STS		DIAS_UNIDADES, R16 
			LDS		R16, DIAS_DECENAS
			INC		R16
			STS		DIAS_DECENAS, R16
			RET
		
		VERIFICAR_31:
			LDS		R18, DIAS_DECENAS
			CPI		R18, 3
			BRNE	SEGUIR_31
			LDS		R16, MES_UNIDADES
			INC		R16
			STS		MES_UNIDADES, R16
			LDI		R16, 1
			STS		DIAS_UNIDADES, R16
			CLR		R16
			STS		DIAS_DECENAS, R16
			RET

	DIAS_28:
		LDS		R16, DIAS_UNIDADES
		INC		R16
		CPI		R16, 9
		BREQ	VERIFICAR_28

		SEGUIR_28:
			CPI		R16, 10
			BRNE	GUARDAR_DIA_CALL
			CLR		R16
			STS		DIAS_UNIDADES, R16 
			LDS		R16, DIAS_DECENAS
			INC		R16
			STS		DIAS_DECENAS, R16
			RET
		
		VERIFICAR_28:
			LDS		R18, DIAS_DECENAS
			CPI		R18, 2
			BRNE	SEGUIR_28
			LDS		R16, MES_UNIDADES
			INC		R16
			STS		MES_UNIDADES, R16
			LDI		R16, 1
			STS		DIAS_UNIDADES, R16
			CLR		R16
			STS		DIAS_DECENAS, R16
			RET

	GUARDAR_DIA_CALL:
		RJMP GUARDAR_DIA

	SEPTIEMBRE:
		LDS		R16, DIAS_UNIDADES
		INC		R16
		CPI		R16, 1
		BREQ	VERIFICAR_30_SEP

		SEGUIR_30_SEP:
			CPI		R16, 10
			BRNE	GUARDAR_DIA_CALL
			CLR		R16
			STS		DIAS_UNIDADES, R16 
			LDS		R16, DIAS_DECENAS
			INC		R16
			STS		DIAS_DECENAS, R16
			RET
		
		VERIFICAR_30_SEP:
			LDS		R18, DIAS_DECENAS
			CPI		R18, 3
			BRNE	SEGUIR_30_SEP
			LDS		R16, MES_UNIDADES
			INC		R16
			STS		MES_UNIDADES, R16
			LDI		R16, 1
			STS		DIAS_UNIDADES, R16
			STS		MES_DECENAS, R16
			CLR		R16
			STS		DIAS_DECENAS, R16 
			STS		MES_UNIDADES, R16

		RET

	DICIEMBRE:
		LDS		R16, DIAS_UNIDADES
		INC		R16
		CPI		R16, 2
		BREQ	VERIFICAR_31_DIC

		SEGUIR_31_DIC:
			CPI		R16, 10
			BRNE	GUARDAR_DIA_CALL
			CLR		R16
			STS		DIAS_UNIDADES, R16 
			LDS		R16, DIAS_DECENAS
			INC		R16
			STS		DIAS_DECENAS, R16
			RET
		
		VERIFICAR_31_DIC:
			LDS		R18, DIAS_DECENAS
			CPI		R18, 3
			BRNE	SEGUIR_31_DIC
			LDS		R16, MES_UNIDADES
			INC		R16
			STS		MES_UNIDADES, R16
			LDI		R16, 1
			STS		DIAS_UNIDADES, R16
			STS		MES_UNIDADES, R16
			CLR		R16
			STS		DIAS_DECENAS, R16
			STS		MES_DECENAS, R16
			RET
	RET
			
SALIDA_MES:
	RET

MOSTRAR_UNI_MIN:
	LDI		ZH, HIGH(disp7seg<<1)
	LDI		ZL, LOW(disp7seg<<1)
	LDS		R18, MIN_UNIDADES
	ADD		ZL, R18
	ADC		ZH, R1
	LPM		R17, Z
	IN		R16, PORTD
	ANDI	R16, 0b10000000//Para conservar el bit 7
	OR		R16, R17
	RET

MOSTRAR_DEC_MIN:
	LDI		ZH, HIGH(disp7seg<<1)
	LDI		ZL, LOW(disp7seg<<1)
	LDS		R18, MIN_DECENAS
	ADD		ZL, R18
	ADC		ZH, R1
	LPM		R17, Z
	IN		R16, PORTD
	ANDI	R16, 0b10000000
