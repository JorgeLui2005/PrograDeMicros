TMR1_ISR:
    PUSH    R16
    PUSH    R21
    PUSH    R22
    IN      R16, SREG
    PUSH    R16

    //Recargar el valor del timer1
    LDI     R16, HIGH(T1VALUE)
    STS     TCNT1H, R16
    LDI     R16, LOW(T1VALUE)
    STS     TCNT1L, R16

    LDS     R21, MIN_UNIDADES
    INC     R21
    CPI     R21, 10 //Comparar con 10 para aumentar decenas
    BRLO    GUARDAR_MIN_UNI
    CLR     R21
    STS     MIN_UNIDADES, R21

    LDS     R21, MIN_DECENAS
    INC     R21
    CPI     R21, 6 //Comparar con 6 para aumentar la hora
    BRLO    GUARDAR_MIN_DEC
    CLR     R21
    STS     MIN_DECENAS, R21

    LDS     R21, HRS_UNIDADES
    INC     R21
    CPI     R21, 10 //Comparar con 10 para aumentar las decenas de hora
    BRLO    GUARDAR_HRS_UNI
    CLR     R21
    STS     HRS_UNIDADES, R21

    LDS     R21, HRS_DECENAS
    INC     R21
    STS     HRS_DECENAS, R21
    RJMP    VERIFICAR_24H

	GUARDAR_HRS_UNI:
		STS     HRS_UNIDADES, R21
		RJMP    VERIFICAR_24H

	VERIFICAR_24H:
		//Comprobar el 24
		LDS     R21, HRS_DECENAS
		CPI     R21, 2
		BRNE    SALIDA_TMR1_ISR

		LDS     R21, HRS_UNIDADES
		CPI     R21, 4
		BRNE    SALIDA_TMR1_ISR

		CLR     R21
		STS     HRS_UNIDADES, R21
		STS     HRS_DECENAS, R21
		
		LDS     R22, BANDERAS
		ORI     R22, 0b00000001
		STS     BANDERAS, R22
		RJMP    SALIDA_TMR1_ISR

	GUARDAR_MIN_DEC:
		STS     MIN_DECENAS, R21
