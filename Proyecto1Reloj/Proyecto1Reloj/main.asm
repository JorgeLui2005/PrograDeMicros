PC_ISR:
	PUSH R16
    PUSH R17
    IN   R16, SREG
    PUSH R16

    IN   R16, PINC //Estado actual 
    LDS  R17, ESTADO_ANT //Estado anterior
    EOR  R17, R16

    STS  ESTADO_ANT, R16 //Nuevo estado
    SBRS R17, 0
    RJMP CHECK_PC1
    SBRC R16, 0
	RJMP SALIDA_ISR
    INC MODO
	CPI MODO, MAX_MODOS
	BRLO SALIDA_ISR
	CLR MODO
	RJMP SALIDA_ISR
	
	CHECK_PC1:
		SBRS R17, 1
		RJMP CHECK_PC2
		SBRS R16, 1
		RJMP APAGAR_ALM
		RJMP SALIDA_ISR

		APAGAR_ALM:
			LDI BANDERA_SUMA, 1
			CBI PORTB,PORTB4
			SBR R29,(1 << 0)
			RJMP SALIDA_ISR

	CHECK_PC2:
		SBRS R17, 2
		RJMP SALIDA_ISR
		SBRS R16, 2
		LDI BANDERA_RESTA, 1

	SALIDA_ISR:
		POP  R16
		OUT  SREG, R16
		POP  R17
		POP  R16
		RETI

